#!/usr/bin/env pwsh
# /opt/mediastack/Set-MediaVolumes.ps1
$ErrorActionPreference = "Stop"
$LibrariesFile = "/opt/mediastack/libraries.json"
$OverrideFile = "/opt/mediastack/docker-compose.override.yml"

if (-not (Test-Path $LibrariesFile)) { Write-Host "[ERROR] $LibrariesFile not found."; exit 1 }

$Libraries = Get-Content $LibrariesFile -Raw | ConvertFrom-Json

Write-Host "[INFO] Verifying physical source directories..."
foreach ($Lib in $Libraries) {
    if (-not (Test-Path -Path $Lib.Source)) {
        Write-Host "[INFO] Creating missing directory: $($Lib.Source)"
        New-Item -Path $Lib.Source -ItemType Directory -Force | Out-Null
    }
}

Write-Host "[INFO] Compiling Docker Compose override matrix..."
$YamlOutput = @("# AUTOGENERATED FILE - DO NOT EDIT MANUALLY", "services:")
$AllServices = $Libraries.Tags | Sort-Object -Unique

foreach ($Service in $AllServices) {
    $ServiceVolumes = @()
    foreach ($Lib in $Libraries) {
        if ($Service -in $Lib.Tags) { $ServiceVolumes += "      - $($Lib.Source):$($Lib.Target)" }
    }
    if ($ServiceVolumes.Count -gt 0) {
        $YamlOutput += "  $Service:`n    volumes:"
        $YamlOutput += $ServiceVolumes
    }
}
$YamlOutput -join "`n" | Out-File -FilePath $OverrideFile -Encoding utf8
Write-Host "[SUCCESS] Volume mappings compiled to $OverrideFile"